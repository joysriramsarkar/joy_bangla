const { DatabaseSync } = require('node:sqlite');
const path = require('node:path');

const dbPath = path.join(__dirname, 'global_bangla.db');
const db = new DatabaseSync(dbPath);

function initDatabase() {
  // 1. Pledges Table
  db.exec(`
    CREATE TABLE IF NOT EXISTS pledges (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      name TEXT NOT NULL,
      country TEXT NOT NULL,
      role TEXT NOT NULL,
      commitment TEXT NOT NULL,
      created_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );
  `);

  // 2. Ideas Table
  db.exec(`
    CREATE TABLE IF NOT EXISTS ideas (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      title TEXT NOT NULL,
      author TEXT NOT NULL,
      country TEXT NOT NULL,
      category TEXT NOT NULL,
      description TEXT NOT NULL,
      votes INTEGER DEFAULT 0,
      created_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );
  `);

  // 3. Tech Glossary Table
  db.exec(`
    CREATE TABLE IF NOT EXISTS glossary (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      term_en TEXT NOT NULL UNIQUE,
      term_bn TEXT NOT NULL,
      phonetic TEXT,
      category TEXT NOT NULL,
      definition TEXT NOT NULL,
      example TEXT NOT NULL,
      votes INTEGER DEFAULT 0
    );
  `);

  // 4. Literature Table
  db.exec(`
    CREATE TABLE IF NOT EXISTS literature (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      title TEXT NOT NULL,
      author TEXT NOT NULL,
      era TEXT NOT NULL,
      genre TEXT NOT NULL,
      excerpt TEXT NOT NULL,
      full_text TEXT NOT NULL,
      read_time TEXT NOT NULL,
      cover_color TEXT NOT NULL
    );
  `);

  // 5. Dictionary Table
  db.exec(`
    CREATE TABLE IF NOT EXISTS dictionary (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      word TEXT NOT NULL UNIQUE,
      transliteration TEXT NOT NULL,
      pos TEXT NOT NULL,
      meaning_bn TEXT NOT NULL,
      meaning_en TEXT NOT NULL,
      example_bn TEXT NOT NULL,
      example_en TEXT NOT NULL,
      etymology TEXT NOT NULL
    );
  `);

  // 6. Voice Contributions Table
  db.exec(`
    CREATE TABLE IF NOT EXISTS voice_samples (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      speaker_name TEXT NOT NULL,
      dialect TEXT NOT NULL,
      sentence TEXT NOT NULL,
      audio_data TEXT,
      duration_sec REAL DEFAULT 3.0,
      verified_count INTEGER DEFAULT 0,
      created_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );
  `);

  // 7. Initiatives Table (১০০টি কৌশলগত উদ্যোগ)
  db.exec(`
    CREATE TABLE IF NOT EXISTS initiatives (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      code TEXT NOT NULL UNIQUE,
      pillar_id TEXT NOT NULL,
      pillar_name TEXT NOT NULL,
      title TEXT NOT NULL,
      short_desc TEXT NOT NULL,
      full_desc TEXT NOT NULL,
      status TEXT NOT NULL,
      priority TEXT NOT NULL,
      target_year TEXT NOT NULL,
      votes INTEGER DEFAULT 0,
      created_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );
  `);

  seedData();
}

